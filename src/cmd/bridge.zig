//! `bridge`: make the Zig port callable from the original code.
//!
//!   JavaScript / TypeScript  port.node (a native Node-API addon for this
//!                            platform) + port.wasm (portable fallback) +
//!                            index.mjs (+ index.d.ts)
//!   Python                   native shared library + port.py, loaded with
//!                            the standard library's ctypes
//!
//! Both bindings keep the original function's name and parameters. After
//! building, every recorded case is replayed through the binding, so the
//! bridged function is checked against the original just like the port.

const std = @import("std");
const builtin = @import("builtin");
const json = std.json;
const cli = @import("../cli.zig");
const lang = @import("../lang.zig");
const proc = @import("../proc.zig");
const cases_mod = @import("../cases.zig");
const runtime = @import("../runtime.zig");
const unit_mod = @import("../unit.zig");
const diff = @import("diff.zig");
const Io = std.Io;

const js_template = @embedFile("../assets/bridge.mjs");
const py_template = @embedFile("../assets/bridge.py");
const napi_source = @embedFile("../assets/napi.zig");

pub const flags = [_]cli.Flag{
    .{ .name = "optimize", .value = "MODE", .help = "debug, safe, fast (default) or small" },
    .{ .name = "no-verify", .help = "skip replaying the recorded cases through the binding" },
    .{ .name = "no-native", .help = "JS/TS: build only the WebAssembly binding, not the native Node addon" },
};

pub const native_lib_name = switch (builtin.os.tag) {
    .windows => "port.dll",
    .macos, .ios => "libport.dylib",
    else => "libport.so",
};

pub fn renderBridgeZig(a: std.mem.Allocator, function: []const u8) ![]u8 {
    var aw: Io.Writer.Allocating = .init(a);
    const w = &aw.writer;
    try w.writeAll(
        \\// Generated by zig-anything bridge. Do not edit.
        \\// C ABI entry points for calling the port from other languages.
        \\const rt = @import("rt.zig");
        \\const port = @import("port.zig");
        \\
        \\const B = rt.Bridge(port.
    );
    try lang.writeZigIdent(w, function);
    try w.writeAll(
        \\);
        \\
        \\export fn za_alloc(n: usize) ?[*]u8 {
        \\    return B.alloc(n);
        \\}
        \\
        \\export fn za_free(p: [*]u8, n: usize) void {
        \\    B.free(p, n);
        \\}
        \\
        \\export fn za_call(args: [*]const u8, len: usize, out_len: *usize) ?[*]u8 {
        \\    return B.call(args, len, out_len);
        \\}
        \\
        \\export fn za_call_batch(args: [*]const u8, len: usize, out_len: *usize) ?[*]u8 {
        \\    return B.callBatch(args, len, out_len);
        \\}
        \\
    );
    return aw.toOwnedSlice();
}

/// The entry file of the native Node addon (src/bridge_node.zig).
pub fn renderNodeZig(a: std.mem.Allocator, function: []const u8) ![]u8 {
    var aw: Io.Writer.Allocating = .init(a);
    const w = &aw.writer;
    try w.writeAll(
        \\// Generated by zig-anything bridge. Do not edit.
        \\// Native Node-API addon entry point; see napi.zig.
        \\const napi = @import("napi.zig");
        \\const port = @import("port.zig");
        \\
        \\comptime {
        \\    @export(&napi.Addon(port.
    );
    try lang.writeZigIdent(w, function);
    try w.writeAll(
        \\).init, .{ .name = "napi_register_module_v1" });
        \\}
        \\
    );
    return aw.toOwnedSlice();
}

fn paramList(a: std.mem.Allocator, params: []const lang.Param) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    for (params, 0..) |p, i| {
        if (i != 0) try out.appendSlice(a, ", ");
        try out.appendSlice(a, p.name);
    }
    return out.items;
}

fn tsType(t: lang.ParamType) []const u8 {
    return switch (t) {
        .number, .int => "number",
        .string => "string",
        .bool => "boolean",
        .number_array, .int_array => "number[]",
        .string_array => "string[]",
        .any => "unknown",
    };
}

pub fn renderDts(a: std.mem.Allocator, m: unit_mod.Manifest) ![]u8 {
    var aw: Io.Writer.Allocating = .init(a);
    const w = &aw.writer;
    try w.print("// Generated by zig-anything bridge. Do not edit.\nexport declare function {s}(", .{m.function});
    for (m.params, 0..) |p, i| {
        if (i != 0) try w.writeAll(", ");
        try w.print("{s}{s}: {s}", .{ p.name, if (p.optional) "?" else "", tsType(p.type) });
    }
    const ret = if (m.returns) |r| tsType(r) else "unknown";
    try w.print("): {s};\n", .{ret});
    try w.print("/** Calls the port once per argument array, crossing the boundary once. */\nexport declare function {s}Batch(calls: Iterable<unknown[]>): {s}[];\n", .{ m.function, ret });
    try w.print("/** Which backend the binding uses. */\nexport declare const backend: 'native' | 'wasm';\nexport default {s};\n", .{m.function});
    return aw.toOwnedSlice();
}

fn fill(a: std.mem.Allocator, template: []const u8, name: []const u8, params: []const u8) ![]u8 {
    const step = try std.mem.replaceOwned(u8, a, template, "__NAME__", name);
    return std.mem.replaceOwned(u8, a, step, "__PARAMS__", params);
}

fn writeFile(c: *cli.Ctx, p: []const u8, data: []const u8) cli.Reported!void {
    Io.Dir.cwd().writeFile(c.io, .{ .sub_path = p, .data = data }) catch |err|
        return c.fail("cannot write {s}: {s}", .{ c.rel(p), @errorName(err) });
}

const Target = enum {
    /// src/bridge.zig -> bridge/port.wasm (JS/TS)
    wasm,
    /// src/bridge.zig -> bridge/port.dll / libport.so / libport.dylib (Python)
    native_lib,
    /// src/bridge_node.zig -> bridge/port.node (JS/TS)
    node_addon,

    fn output(t: Target) []const u8 {
        return switch (t) {
            .wasm => "bridge/port.wasm",
            .native_lib => "bridge/" ++ native_lib_name,
            .node_addon => "bridge/port.node",
        };
    }
};

/// Compiles one bridge artifact. Returns the compiler's error output, or
/// null on success.
fn compile(c: *cli.Ctx, u: unit_mod.Unit, t: Target, mode: unit_mod.Optimize) cli.Reported!?[]const u8 {
    const emit = std.fmt.allocPrint(c.arena, "-femit-bin={s}", .{t.output()}) catch return c.fail("out of memory", .{});
    const zig = u.cfg.config.zig;
    const o = @tagName(mode);
    const argv: []const []const u8 = switch (t) {
        .wasm => &.{ zig, "build-exe", "src/bridge.zig", "-target", "wasm32-freestanding", "-fno-entry", "-rdynamic", "-O", o, "-fstrip", emit },
        .native_lib => &.{ zig, "build-lib", "src/bridge.zig", "-dynamic", "-O", o, "-fstrip", emit },
        // The addon resolves Node-API with dlsym outside Windows, so it links libc there.
        .node_addon => if (builtin.os.tag == .windows)
            &.{ zig, "build-lib", "src/bridge_node.zig", "-dynamic", "-O", o, "-fstrip", emit }
        else
            &.{ zig, "build-lib", "src/bridge_node.zig", "-dynamic", "-lc", "-O", o, "-fstrip", emit },
    };
    const r = try proc.run(c, argv, .{
        .cwd = u.dir,
        .timeout_s = u.cfg.config.timeout,
        .missing_hint = "install Zig from https://ziglang.org/download/ or set ZIG / \"zig\" in zig-anything.json",
    });
    // Linker side products nobody loads (Windows import libraries, objects).
    for ([_][]const u8{ "bridge/bridge.lib", "bridge/port.lib", "bridge/port.pdb", "bridge/port.wasm.o", "bridge/bridge.obj", "bridge/bridge_node.lib", "bridge/bridge_node.obj", "bridge/port.node.pdb", "bridge/port.exp" }) |leftover| {
        Io.Dir.cwd().deleteFile(c.io, u.path(c.arena, leftover)) catch {};
    }
    return if (r.ok) null else r.stderr;
}

fn printCompileErrors(c: *cli.Ctx, stderr: []const u8) void {
    c.out.flush() catch {};
    c.err.writeAll(stderr) catch {};
    c.err.flush() catch {};
}

/// The job that replays every recorded case through `binding`. With
/// `force_wasm`, index.mjs is told to skip the native addon.
fn verifyJob(c: *cli.Ctx, u: unit_mod.Unit, binding: []const u8, out_name: []const u8, force_wasm: bool, effects: bool) cli.Reported!proc.Job {
    const job = try runtime.prepare(c, u, .run, u.path(c.arena, unit_mod.cases_name), u.workPath(c.arena, out_name), .{ .source = binding, .effects = effects });
    // `prepare` allocates a fresh, mutable map for every job.
    if (force_wasm) @constCast(job.opts.environ_map.?).put("ZIG_ANYTHING_BRIDGE", "wasm") catch return c.fail("out of memory", .{});
    return job;
}

const Verdict = struct { matched: usize, compared: usize, first_bad: ?usize };

pub fn compareReplay(c: *cli.Ctx, u: unit_mod.Unit, cs: []const cases_mod.Case, out_name: []const u8, effects: bool) Verdict {
    const opts: diff.Options = .{ .tolerance = u.cfg.config.tolerance, .effects = effects, .doubles = runtime.adapterOf(u).numbers_are_doubles };
    const text = Io.Dir.cwd().readFileAlloc(c.io, u.workPath(c.arena, out_name), c.arena, .unlimited) catch "";
    var it: cases_mod.LineIterator = .{ .rest = text };
    var v: Verdict = .{ .matched = 0, .compared = 0, .first_bad = null };
    for (cs) |*case| {
        const line = it.next() orelse break;
        if (case.flaky) continue;
        v.compared += 1;
        const got = json.parseFromSliceLeaky(json.Value, c.arena, line, .{}) catch continue;
        if (diff.classify(case.expect, got, case.args, opts) == null) {
            v.matched += 1;
        } else if (v.first_bad == null) v.first_bad = case.id;
    }
    return v;
}

pub const BuildOptions = struct {
    mode: unit_mod.Optimize = .fast,
    /// JS/TS: also build the native Node addon.
    native: bool = true,
    verify: bool = true,
    /// Compare side effects when replaying (from the recording).
    effects: bool = false,
};

pub const Built = struct {
    /// The binding the original code imports (index.mjs or port.py).
    binding: []const u8,
    /// Every replay through the binding matched (true when not verified).
    verified: bool,
};

pub fn run(c: *cli.Ctx, args: cli.Parsed) !u8 {
    const u = try unit_mod.load(c, args.pos(0));
    const m = u.manifest;
    const mode: unit_mod.Optimize = if (args.get("optimize")) |v|
        unit_mod.Optimize.parse(v) orelse return c.fail("--optimize must be debug, safe, fast or small (got '{s}')", .{v})
    else
        .fast;
    const js = !u.isCli() and runtime.adapterOf(u).bridge == .node;
    const built = (try buildAndVerify(c, u, .{
        .mode = mode,
        .native = !args.has("no-native"),
        .verify = !args.has("no-verify"),
        .effects = !u.isCli() and diff.effectsWanted(c, u, args),
    })) orelse return 1;
    const binding = built.binding;

    // Crossing the bridge costs ~1 µs (Node) to a few µs (Python) per call,
    // mostly JSON encoding. Warn when the benchmark says that dominates.
    if (Io.Dir.cwd().readFileAlloc(c.io, u.workPath(c.arena, "bench.json"), c.arena, .limited(1 << 16))) |bt| {
        if (json.parseFromSliceLeaky(json.Value, c.arena, bt, .{})) |bv| {
            const per_call: ?f64 = if (bv == .object) if (bv.object.get("original_ns_per_call")) |v| switch (v) {
                .float => |x| x,
                .integer => |x| @floatFromInt(x),
                else => null,
            } else null else null;
            if (per_call) |ns| if (ns < 3000) {
                c.hint("the original takes {d:.0} ns per call, close to the cost of crossing the bridge; use {s}{s} for many calls, or port the caller too", .{ ns, m.function, if (js) "Batch()" else "_batch()" });
            };
        } else |_| {}
    } else |_| {}

    // How to use it from the original code.
    const src_dir = std.fs.path.dirname(u.source_abs) orelse u.dir;
    const from_src = std.fs.path.relativeAlloc(c.arena, c.cwd, c.env, src_dir, binding) catch c.arena.dupe(u8, binding) catch return c.fail("out of memory", .{});
    std.mem.replaceScalar(u8, from_src, '\\', '/');
    if (js) {
        const spec = if (std.mem.startsWith(u8, from_src, ".")) from_src else std.fmt.allocPrint(c.arena, "./{s}", .{from_src}) catch from_src;
        c.print("\nuse it from {s}:\n  import {{ {s} }} from '{s}';\n", .{ c.rel(u.source_abs), m.function, spec });
    } else {
        c.print("\nuse it from {s}:\n", .{c.rel(u.source_abs)});
        c.print("  import importlib.util, os\n", .{});
        c.print("  _spec = importlib.util.spec_from_file_location(\"{s}_zig\", os.path.join(os.path.dirname(__file__), \"{s}\"))\n", .{ m.function, from_src });
        c.print("  _mod = importlib.util.module_from_spec(_spec); _spec.loader.exec_module(_mod)\n  {s} = _mod.{s}\n", .{ m.function, m.function });
    }
    c.print("or wire it in with verification and automatic rollback: zig-anything integrate {s}\n", .{c.rel(u.dir)});
    return if (built.verified) 0 else 1;
}

/// Builds the bridge for `u` and replays the recorded cases through it.
/// Returns null (after reporting) when the build fails.
pub fn buildAndVerify(c: *cli.Ctx, u: unit_mod.Unit, o: BuildOptions) cli.Reported!?Built {
    const m = u.manifest;
    if (u.isCli()) {
        c.hint("a ported program is already standalone: {s}/zig-out/bin/port", .{c.rel(u.dir)});
        return c.fail("bridge is for function units", .{});
    }
    if (unit_mod.portIsStub(c, u)) {
        c.hint("finish the port first; `zig-anything gate {s}` shows what is left", .{c.rel(u.dir)});
        return c.fail("src/port.zig still has the {s} marker", .{unit_mod.todo_marker});
    }
    const mode = o.mode;
    const js = runtime.adapterOf(u).bridge == .node;

    try unit_mod.refreshRuntime(c, u);
    try writeFile(c, u.path(c.arena, "src/bridge.zig"), renderBridgeZig(c.arena, m.function) catch return c.fail("out of memory", .{}));
    const bridge_dir = u.path(c.arena, "bridge");
    Io.Dir.cwd().createDirPath(c.io, bridge_dir) catch |err| return c.fail("cannot create {s}: {s}", .{ c.rel(bridge_dir), @errorName(err) });

    const want_native = js and o.native;
    if (want_native) {
        try writeFile(c, u.path(c.arena, "src/napi.zig"), napi_source);
        try writeFile(c, u.path(c.arena, "src/bridge_node.zig"), renderNodeZig(c.arena, m.function) catch return c.fail("out of memory", .{}));
    }

    c.print("compiling {s} to {s}...\n", .{ m.function, if (want_native) "a native Node addon and WebAssembly" else if (js) "WebAssembly" else "a native library" });
    c.out.flush() catch {};
    if (try compile(c, u, if (js) .wasm else .native_lib, mode)) |stderr| {
        printCompileErrors(c, stderr);
        c.report("bridge build failed; fix the compile errors above", .{});
        return null;
    }
    var native_ok = false;
    if (want_native) {
        if (try compile(c, u, .node_addon, mode)) |stderr| {
            // The WebAssembly build works everywhere, so this is not fatal.
            printCompileErrors(c, stderr);
            c.hint("the native addon did not build; index.mjs will use WebAssembly (`--no-native` skips the attempt)", .{});
        } else native_ok = true;
    }
    if (!native_ok) Io.Dir.cwd().deleteFile(c.io, u.path(c.arena, "bridge/port.node")) catch {};

    const params = paramList(c.arena, m.params) catch return c.fail("out of memory", .{});
    const binding = if (js) u.path(c.arena, "bridge/index.mjs") else u.path(c.arena, "bridge/port.py");
    try writeFile(c, binding, fill(c.arena, if (js) js_template else py_template, m.function, params) catch return c.fail("out of memory", .{}));
    if (m.language == .typescript) {
        const dts = renderDts(c.arena, m) catch return c.fail("out of memory", .{});
        try writeFile(c, u.path(c.arena, "bridge/index.d.ts"), dts);
        // TypeScript looks for the types of `./index.mjs` in index.d.mts.
        try writeFile(c, u.path(c.arena, "bridge/index.d.mts"), dts);
    }
    c.print("{s}bridged{s} {s} -> {s}", .{ c.s(.green), c.s(.reset), m.function, c.rel(binding) });
    for ([_]Target{ .node_addon, .wasm, .native_lib }) |t| {
        if (t == .node_addon and !native_ok) continue;
        if ((t == .native_lib) == js) continue;
        const st = Io.Dir.cwd().statFile(c.io, u.path(c.arena, t.output()), .{}) catch continue;
        c.print("  ({s}, {d} KB)", .{ std.fs.path.basename(t.output()), (st.size + 1023) / 1024 });
    }
    c.print("\n", .{});

    var verified = true;
    if (o.verify) {
        const cs = try cases_mod.load(c, u);
        try u.ensureWorkDir(c);
        const effects = o.effects;
        // Every backend the binding can pick is checked, concurrently: the
        // native addon (when built) and WebAssembly.
        const Backend = struct { label: []const u8, out_name: []const u8, force_wasm: bool };
        const backends: []const Backend = if (!js)
            &.{.{ .label = "", .out_name = "bridge.jsonl", .force_wasm = false }}
        else if (native_ok)
            &.{ .{ .label = " (native addon)", .out_name = "bridge.jsonl", .force_wasm = false }, .{ .label = " (WebAssembly)", .out_name = "bridge.wasm.jsonl", .force_wasm = true } }
        else
            &.{.{ .label = "", .out_name = "bridge.jsonl", .force_wasm = true }};
        var jobs: [2]proc.Job = undefined;
        for (backends, 0..) |bk, i| jobs[i] = try verifyJob(c, u, binding, bk.out_name, bk.force_wasm, effects);
        const results = try proc.runManyQuiet(c, jobs[0..backends.len]);
        for (backends, results, 0..) |bk, res, i| {
            const r = res catch |err| return proc.reportRunError(c, jobs[i].argv, jobs[i].opts, err);
            if (!r.ok) return runtime.reportFailure(c, u, r);
            const v = compareReplay(c, u, cs, bk.out_name, effects);
            const ok = v.compared > 0 and v.matched == v.compared;
            c.print("{s}{d}/{d}{s} recorded cases match through the bridge{s}\n", .{ if (ok) c.s(.green) else c.s(.red), v.matched, v.compared, c.s(.reset), bk.label });
            if (v.first_bad) |id| c.print("  first mismatch: case {d}; run `zig-anything diff {s}` for details\n", .{ id, c.rel(u.dir) });
            if (!ok) verified = false;
        }
    }
    return .{ .binding = binding, .verified = verified };
}

test "bridge entry file and type declarations" {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const z = try renderBridgeZig(a, "fuzzyScore");
    try std.testing.expect(std.mem.indexOf(u8, z, "rt.Bridge(port.fuzzyScore)") != null);
    try std.testing.expect(std.mem.indexOf(u8, z, "export fn za_call(") != null);
    const d = try renderDts(a, .{
        .name = "f",
        .language = .typescript,
        .source = "x.ts",
        .function = "f",
        .params = &.{ .{ .name = "q", .type = .string }, .{ .name = "n", .type = .int, .optional = true } },
        .returns = .number_array,
    });
    try std.testing.expect(std.mem.indexOf(u8, d, "export declare function f(q: string, n?: number): number[];") != null);
    const js = try fill(a, js_template, "f", "q, n");
    try std.testing.expect(std.mem.indexOf(u8, js, "function f(q, n) {\n      return native.call(q, n);") != null);
    try std.testing.expect(std.mem.indexOf(u8, js, "function f(q, n) {\n      return call([q, n]);") != null);
    try std.testing.expect(std.mem.indexOf(u8, js, "export function fBatch(calls)") != null);
    try std.testing.expect(std.mem.indexOf(u8, js, "__NAME__") == null and std.mem.indexOf(u8, js, "__PARAMS__") == null);
    const node = try renderNodeZig(a, "fuzzyScore");
    try std.testing.expect(std.mem.indexOf(u8, node, "@export(&napi.Addon(port.fuzzyScore).init, .{ .name = \"napi_register_module_v1\" });") != null);
}
