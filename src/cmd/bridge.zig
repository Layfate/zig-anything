//! `bridge`: make the Zig port callable from the original code.
//!
//!   JavaScript / TypeScript  port.wasm + index.mjs (+ index.d.ts); Node loads
//!                            it with its built-in WebAssembly support
//!   Python                   native shared library + port.py, loaded with
//!                            the standard library's ctypes
//!
//! Both bindings keep the original function's name and parameters. After
//! building, every recorded case is replayed through the binding, so the
//! bridged function is checked against the original just like the port.

const std = @import("std");
const builtin = @import("builtin");
const json = std.json;
const cli = @import("../cli.zig");
const lang = @import("../lang.zig");
const proc = @import("../proc.zig");
const cases_mod = @import("../cases.zig");
const runtime = @import("../runtime.zig");
const unit_mod = @import("../unit.zig");
const diff = @import("diff.zig");
const Io = std.Io;

const js_template = @embedFile("../assets/bridge.mjs");
const py_template = @embedFile("../assets/bridge.py");

pub const flags = [_]cli.Flag{
    .{ .name = "optimize", .value = "MODE", .help = "debug, safe, fast (default) or small" },
    .{ .name = "no-verify", .help = "skip replaying the recorded cases through the binding" },
};

pub const native_lib_name = switch (builtin.os.tag) {
    .windows => "port.dll",
    .macos, .ios => "libport.dylib",
    else => "libport.so",
};

pub fn renderBridgeZig(a: std.mem.Allocator, function: []const u8) ![]u8 {
    var aw: Io.Writer.Allocating = .init(a);
    const w = &aw.writer;
    try w.writeAll(
        \\// Generated by zig-anything bridge. Do not edit.
        \\// C ABI entry points for calling the port from other languages.
        \\const rt = @import("rt.zig");
        \\const port = @import("port.zig");
        \\
        \\const B = rt.Bridge(port.
    );
    try lang.writeZigIdent(w, function);
    try w.writeAll(
        \\);
        \\
        \\export fn za_alloc(n: usize) ?[*]u8 {
        \\    return B.alloc(n);
        \\}
        \\
        \\export fn za_free(p: [*]u8, n: usize) void {
        \\    B.free(p, n);
        \\}
        \\
        \\export fn za_call(args: [*]const u8, len: usize, out_len: *usize) ?[*]u8 {
        \\    return B.call(args, len, out_len);
        \\}
        \\
        \\export fn za_call_batch(args: [*]const u8, len: usize, out_len: *usize) ?[*]u8 {
        \\    return B.callBatch(args, len, out_len);
        \\}
        \\
    );
    return aw.toOwnedSlice();
}

fn paramList(a: std.mem.Allocator, params: []const lang.Param) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    for (params, 0..) |p, i| {
        if (i != 0) try out.appendSlice(a, ", ");
        try out.appendSlice(a, p.name);
    }
    return out.items;
}

fn tsType(t: lang.ParamType) []const u8 {
    return switch (t) {
        .number, .int => "number",
        .string => "string",
        .bool => "boolean",
        .number_array, .int_array => "number[]",
        .string_array => "string[]",
        .any => "unknown",
    };
}

pub fn renderDts(a: std.mem.Allocator, m: unit_mod.Manifest) ![]u8 {
    var aw: Io.Writer.Allocating = .init(a);
    const w = &aw.writer;
    try w.print("// Generated by zig-anything bridge. Do not edit.\nexport declare function {s}(", .{m.function});
    for (m.params, 0..) |p, i| {
        if (i != 0) try w.writeAll(", ");
        try w.print("{s}{s}: {s}", .{ p.name, if (p.optional) "?" else "", tsType(p.type) });
    }
    try w.print("): {s};\nexport default {s};\n", .{ if (m.returns) |r| tsType(r) else "unknown", m.function });
    return aw.toOwnedSlice();
}

fn fill(a: std.mem.Allocator, template: []const u8, name: []const u8, params: []const u8) ![]u8 {
    const step = try std.mem.replaceOwned(u8, a, template, "__NAME__", name);
    return std.mem.replaceOwned(u8, a, step, "__PARAMS__", params);
}

fn writeFile(c: *cli.Ctx, p: []const u8, data: []const u8) cli.Reported!void {
    Io.Dir.cwd().writeFile(c.io, .{ .sub_path = p, .data = data }) catch |err|
        return c.fail("cannot write {s}: {s}", .{ c.rel(p), @errorName(err) });
}

/// Compiles src/bridge.zig. Returns false (after printing compiler output)
/// when compilation fails.
fn compile(c: *cli.Ctx, u: unit_mod.Unit, js: bool, mode: unit_mod.Optimize) cli.Reported!bool {
    const out = if (js) "bridge/port.wasm" else "bridge/" ++ native_lib_name;
    const emit = std.fmt.allocPrint(c.arena, "-femit-bin={s}", .{out}) catch return c.fail("out of memory", .{});
    const zig = u.cfg.config.zig;
    const argv: []const []const u8 = if (js)
        &.{ zig, "build-exe", "src/bridge.zig", "-target", "wasm32-freestanding", "-fno-entry", "-rdynamic", "-O", @tagName(mode), "-fstrip", emit }
    else
        &.{ zig, "build-lib", "src/bridge.zig", "-dynamic", "-O", @tagName(mode), "-fstrip", emit };
    const r = try proc.run(c, argv, .{
        .cwd = u.dir,
        .timeout_s = u.cfg.config.timeout,
        .missing_hint = "install Zig from https://ziglang.org/download/ or set ZIG / \"zig\" in zig-anything.json",
    });
    if (!r.ok) {
        c.out.flush() catch {};
        c.err.writeAll(r.stderr) catch {};
        c.err.flush() catch {};
        return false;
    }
    // Linker side products nobody loads (Windows import library, objects).
    for ([_][]const u8{ "bridge/bridge.lib", "bridge/port.lib", "bridge/port.pdb", "bridge/port.wasm.o", "bridge/bridge.obj" }) |leftover| {
        Io.Dir.cwd().deleteFile(c.io, u.path(c.arena, leftover)) catch {};
    }
    return true;
}

pub fn run(c: *cli.Ctx, args: cli.Parsed) !u8 {
    const u = try unit_mod.load(c, args.pos(0));
    const m = u.manifest;
    if (u.isCli()) {
        c.hint("a ported program is already standalone: {s}/zig-out/bin/port", .{c.rel(u.dir)});
        return c.fail("bridge is for function units", .{});
    }
    if (unit_mod.portIsStub(c, u)) {
        c.hint("finish the port first; `zig-anything gate {s}` shows what is left", .{c.rel(u.dir)});
        return c.fail("src/port.zig still has the {s} marker", .{unit_mod.todo_marker});
    }
    const mode: unit_mod.Optimize = if (args.get("optimize")) |v|
        unit_mod.Optimize.parse(v) orelse return c.fail("--optimize must be debug, safe, fast or small (got '{s}')", .{v})
    else
        .fast;
    const js = m.lang_().isJs();

    try unit_mod.refreshRuntime(c, u);
    try writeFile(c, u.path(c.arena, "src/bridge.zig"), renderBridgeZig(c.arena, m.function) catch return c.fail("out of memory", .{}));
    const bridge_dir = u.path(c.arena, "bridge");
    Io.Dir.cwd().createDirPath(c.io, bridge_dir) catch |err| return c.fail("cannot create {s}: {s}", .{ c.rel(bridge_dir), @errorName(err) });

    c.print("compiling {s} to {s}...\n", .{ m.function, if (js) "WebAssembly" else "a native library" });
    c.out.flush() catch {};
    if (!try compile(c, u, js, mode)) {
        c.report("bridge build failed; fix the compile errors above", .{});
        return 1;
    }

    const params = paramList(c.arena, m.params) catch return c.fail("out of memory", .{});
    const binding = if (js) u.path(c.arena, "bridge/index.mjs") else u.path(c.arena, "bridge/port.py");
    try writeFile(c, binding, fill(c.arena, if (js) js_template else py_template, m.function, params) catch return c.fail("out of memory", .{}));
    if (m.language == .typescript) {
        try writeFile(c, u.path(c.arena, "bridge/index.d.ts"), renderDts(c.arena, m) catch return c.fail("out of memory", .{}));
    }
    const artifact = u.path(c.arena, if (js) "bridge/port.wasm" else "bridge/" ++ native_lib_name);
    const size = (Io.Dir.cwd().statFile(c.io, artifact, .{}) catch null);
    c.print("{s}bridged{s} {s} -> {s}", .{ c.s(.green), c.s(.reset), m.function, c.rel(binding) });
    if (size) |st| c.print("  ({s}, {d} KB)", .{ std.fs.path.basename(artifact), (st.size + 1023) / 1024 });
    c.print("\n", .{});

    var exit: u8 = 0;
    if (!args.has("no-verify")) {
        const cs = try cases_mod.load(c, u);
        try u.ensureWorkDir(c);
        const out_path = u.workPath(c.arena, "bridge.jsonl");
        const r = try runtime.invokeSource(c, u, binding, .run, u.path(c.arena, unit_mod.cases_name), out_path, 1);
        if (!r.ok) return runtime.reportFailure(c, u, r);
        const text = Io.Dir.cwd().readFileAlloc(c.io, out_path, c.arena, .unlimited) catch "";
        var it: cases_mod.LineIterator = .{ .rest = text };
        var matched: usize = 0;
        var compared: usize = 0;
        var first_bad: ?*const cases_mod.Case = null;
        for (cs) |*case| {
            const line = it.next() orelse break;
            if (case.flaky) continue;
            compared += 1;
            const got = json.parseFromSliceLeaky(json.Value, c.arena, line, .{}) catch continue;
            if (diff.classify(case.expect, got, .{ .tolerance = u.cfg.config.tolerance }) == null) {
                matched += 1;
            } else if (first_bad == null) first_bad = case;
        }
        const ok = compared > 0 and matched == compared;
        c.print("{s}{d}/{d}{s} recorded cases match through the bridge\n", .{ if (ok) c.s(.green) else c.s(.red), matched, compared, c.s(.reset) });
        if (first_bad) |case| c.print("  first mismatch: case {d}; run `zig-anything diff {s}` for details\n", .{ case.id, c.rel(u.dir) });
        if (!ok) exit = 1;
    }

    // Crossing the bridge costs ~1 µs (Node) to a few µs (Python) per call,
    // mostly JSON encoding. Warn when the benchmark says that dominates.
    if (Io.Dir.cwd().readFileAlloc(c.io, u.workPath(c.arena, "bench.json"), c.arena, .limited(1 << 16))) |bt| {
        if (json.parseFromSliceLeaky(json.Value, c.arena, bt, .{})) |bv| {
            const per_call: ?f64 = if (bv == .object) if (bv.object.get("original_ns_per_call")) |v| switch (v) {
                .float => |x| x,
                .integer => |x| @floatFromInt(x),
                else => null,
            } else null else null;
            if (per_call) |ns| if (ns < 3000) {
                c.hint("the original takes {d:.0} ns per call, less than a bridge crossing (~1-3 µs); use {s}{s} for many calls, or port the caller too", .{ ns, m.function, if (js) "Batch()" else "_batch()" });
            };
        } else |_| {}
    } else |_| {}

    // How to use it from the original code.
    const src_dir = std.fs.path.dirname(u.source_abs) orelse u.dir;
    const from_src = std.fs.path.relativeAlloc(c.arena, c.cwd, c.env, src_dir, binding) catch c.arena.dupe(u8, binding) catch return c.fail("out of memory", .{});
    std.mem.replaceScalar(u8, from_src, '\\', '/');
    if (js) {
        const spec = if (std.mem.startsWith(u8, from_src, ".")) from_src else std.fmt.allocPrint(c.arena, "./{s}", .{from_src}) catch from_src;
        c.print("\nuse it from {s}:\n  import {{ {s} }} from '{s}';\n", .{ c.rel(u.source_abs), m.function, spec });
    } else {
        c.print("\nuse it from {s}:\n", .{c.rel(u.source_abs)});
        c.print("  import importlib.util, os\n", .{});
        c.print("  _spec = importlib.util.spec_from_file_location(\"{s}_zig\", os.path.join(os.path.dirname(__file__), \"{s}\"))\n", .{ m.function, from_src });
        c.print("  _mod = importlib.util.module_from_spec(_spec); _spec.loader.exec_module(_mod)\n  {s} = _mod.{s}\n", .{ m.function, m.function });
    }
    return exit;
}

test "bridge entry file and type declarations" {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    const z = try renderBridgeZig(a, "fuzzyScore");
    try std.testing.expect(std.mem.indexOf(u8, z, "rt.Bridge(port.fuzzyScore)") != null);
    try std.testing.expect(std.mem.indexOf(u8, z, "export fn za_call(") != null);
    const d = try renderDts(a, .{
        .name = "f",
        .language = .typescript,
        .source = "x.ts",
        .function = "f",
        .params = &.{ .{ .name = "q", .type = .string }, .{ .name = "n", .type = .int, .optional = true } },
        .returns = .number_array,
    });
    try std.testing.expect(std.mem.indexOf(u8, d, "export declare function f(q: string, n?: number): number[];") != null);
    const js = try fill(a, js_template, "f", "q, n");
    try std.testing.expect(std.mem.indexOf(u8, js, "export function f(q, n) {\n  return call([q, n]);") != null);
    try std.testing.expect(std.mem.indexOf(u8, js, "__") == null or std.mem.indexOf(u8, js, "__NAME__") == null);
}
